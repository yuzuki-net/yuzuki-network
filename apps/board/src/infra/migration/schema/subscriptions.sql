-- Fast eligibility view for proxy node entitlement push (`entitled_ids_for_node`).
-- Accounts are eligible if active AND they hold at least one active, unrevoked,
-- unexpired quota grant that has remaining bytes or is due for a cycle reset.
CREATE VIEW account_quota_status AS
SELECT
    a.id AS account_id,
    a.used_bytes AS lifetime_used_bytes,
    a.active AND EXISTS (
        SELECT 1
        FROM account_quotas aq
        WHERE aq.account_id = a.id
          AND aq.revoked = false
          AND aq.starts_at <= statement_timestamp()
          AND (aq.expires_at IS NULL OR aq.expires_at > statement_timestamp())
          AND (
              aq.quota_bytes IS NULL
              OR aq.used_bytes < aq.quota_bytes
              OR (
                  aq.reset_mode = 'cycle'
                  AND aq.cycle_ends_at IS NOT NULL
                  AND aq.cycle_ends_at <= statement_timestamp()
              )
          )
    ) AS eligible
FROM accounts a;
