-- Stackable quota instances granted to an account (supports multiple active plans/add-ons,
-- calendar-accurate months/years/days/hours or unlimited duration, cycle reset or one-time pack).
CREATE TABLE account_quotas (
    id uuid PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    plan_id uuid REFERENCES quota_plans(id) ON DELETE SET NULL,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    quota_bytes bigint CHECK (quota_bytes >= 0),
    used_bytes bigint NOT NULL DEFAULT 0 CHECK (used_bytes >= 0),
    duration_kind text NOT NULL DEFAULT 'unlimited'
        CHECK (duration_kind IN ('unlimited', 'hours', 'days', 'months', 'years')),
    duration_value integer CHECK (duration_value BETWEEN 1 AND 36500),
    reset_mode text NOT NULL DEFAULT 'none'
        CHECK (reset_mode IN ('none', 'cycle')),
    anchor_at timestamptz NOT NULL DEFAULT now(),
    cycle_index integer NOT NULL DEFAULT 0 CHECK (cycle_index >= 0),
    starts_at timestamptz NOT NULL DEFAULT now(),
    cycle_starts_at timestamptz NOT NULL DEFAULT now(),
    cycle_ends_at timestamptz,
    expires_at timestamptz,
    max_devices integer CHECK (max_devices BETWEEN 0 AND 1000),
    priority integer NOT NULL DEFAULT 0,
    revoked boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((duration_kind = 'unlimited') = (duration_value IS NULL)),
    CHECK (reset_mode <> 'cycle' OR duration_kind <> 'unlimited')
);
CREATE INDEX account_quotas_by_account ON account_quotas (account_id, revoked, starts_at);

-- Optional account-level overrides for device limit & per-format link caps
CREATE TABLE account_quota_policy (
    account_id uuid PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    max_devices integer CHECK (max_devices BETWEEN 0 AND 1000),
    max_links_xray integer CHECK (max_links_xray BETWEEN 0 AND 100),
    max_links_sing_box integer CHECK (max_links_sing_box BETWEEN 0 AND 100),
    max_links_mihomo integer CHECK (max_links_mihomo BETWEEN 0 AND 100),
    max_links_universal integer CHECK (max_links_universal BETWEEN 0 AND 100)
);

CREATE TABLE subscription_links (
    id uuid PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    format smallint NOT NULL CHECK (format BETWEEN 0 AND 3),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    token text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz
);
CREATE INDEX subscription_links_by_account ON subscription_links (account_id, format);

CREATE TABLE subscription_devices (
    id uuid PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    device_hash text NOT NULL,
    client_name text NOT NULL,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (account_id, device_hash)
);
CREATE INDEX subscription_devices_by_account ON subscription_devices (account_id, last_seen_at DESC, id);
CREATE INDEX subscription_devices_recent ON subscription_devices (last_seen_at);
